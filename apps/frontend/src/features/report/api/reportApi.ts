import apiClient from '../../../shared/api/client';

/**
 * 棚卸表レポートダウンロード。
 *
 * @param id 棚卸 ID
 * @returns PDF ファイルの Blob データ
 */
export const downloadInventoryReport = (id: number) =>
  apiClient.get(`/inventories/${id}/report`, { responseType: 'blob' });
